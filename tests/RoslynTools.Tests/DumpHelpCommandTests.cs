using System.CommandLine;
using System.Text;
using RoslynTools;
using RoslynTools.Commands;
using RoslynTools.Core;

namespace RoslynTools.Tests;

/// <summary>
/// Unit tests for DumpHelpCommand helper methods extracted in US-033:
///   - BuildHeader
///   - BuildContents
///   - BuildGroupSection
///   - BuildCommandSection
/// Each helper is tested in isolation with a minimal synthetic registry.
/// </summary>
public sealed class DumpHelpCommandTests
{
    // ── helpers ───────────────────────────────────────────────────────────────────

    private static (Command Cmd, RtCommandInfo Info) MakeEntry(
        string name,
        string category,
        string description = "A description",
        bool mutates = false,
        bool jsonOutput = false,
        string[]? aliases = null,
        string[]? knownIssues = null,
        string[]? examples = null)
    {
        var info = new RtCommandInfo(
            Name: name,
            Mutates: mutates,
            JsonOutput: jsonOutput,
            Category: category,
            WhenToUse: "Use when needed.",
            Examples: examples ?? [$"rt {category} {name}"],
            KnownIssues: knownIssues,
            Aliases: aliases);

        var cmd = new Command(name, description);
        return (cmd, info);
    }

    // ── BuildHeader ───────────────────────────────────────────────────────────────

    [Fact]
    public void BuildHeader_emits_h1_title()
    {
        var sb = new StringBuilder();
        var registry = new List<(Command, RtCommandInfo)> { MakeEntry("foo", "inspect") };

        DumpHelpCommand.BuildHeader(sb, registry);

        Assert.Contains("# rt Commands", sb.ToString());
    }

    [Fact]
    public void BuildHeader_includes_total_count()
    {
        var sb = new StringBuilder();
        var registry = new List<(Command, RtCommandInfo)>
        {
            MakeEntry("foo", "inspect"),
            MakeEntry("bar", "analyze"),
        };

        DumpHelpCommand.BuildHeader(sb, registry);

        Assert.Contains("**2**", sb.ToString());
    }

    [Fact]
    public void BuildHeader_includes_autogenerated_notice()
    {
        var sb = new StringBuilder();
        var registry = new List<(Command, RtCommandInfo)> { MakeEntry("foo", "inspect") };

        DumpHelpCommand.BuildHeader(sb, registry);

        Assert.Contains("Auto-generated", sb.ToString());
    }

    // ── BuildContents ─────────────────────────────────────────────────────────────

    [Fact]
    public void BuildContents_emits_Contents_heading()
    {
        var sb = new StringBuilder();
        var groups = new List<(Command, RtCommandInfo)> { MakeEntry("describe", "inspect") }
            .GroupBy(e => e.Item2.Category)
            .OrderBy(g => g.Key);

        DumpHelpCommand.BuildContents(sb, groups);

        Assert.Contains("## Contents", sb.ToString());
    }

    [Fact]
    public void BuildContents_lists_each_group_key()
    {
        var sb = new StringBuilder();
        var groups = new List<(Command, RtCommandInfo)>
            {
                MakeEntry("describe", "inspect"),
                MakeEntry("circular-deps", "analyze"),
            }
            .GroupBy(e => e.Item2.Category)
            .OrderBy(g => g.Key);

        DumpHelpCommand.BuildContents(sb, groups);

        var output = sb.ToString();
        Assert.Contains("rt inspect", output);
        Assert.Contains("rt analyze", output);
    }

    [Fact]
    public void BuildContents_includes_anchor_link_for_command_name()
    {
        var sb = new StringBuilder();
        var groups = new List<(Command, RtCommandInfo)> { MakeEntry("describe", "inspect") }
            .GroupBy(e => e.Item2.Category)
            .OrderBy(g => g.Key);

        DumpHelpCommand.BuildContents(sb, groups);

        Assert.Contains("[`describe`](#describe)", sb.ToString());
    }

    [Fact]
    public void BuildContents_includes_aliases_when_present()
    {
        var sb = new StringBuilder();
        var groups = new List<(Command, RtCommandInfo)>
            {
                MakeEntry("find-refs", "inspect", aliases: ["refs"]),
            }
            .GroupBy(e => e.Item2.Category)
            .OrderBy(g => g.Key);

        DumpHelpCommand.BuildContents(sb, groups);

        Assert.Contains("refs", sb.ToString());
    }

    // ── BuildGroupSection ─────────────────────────────────────────────────────────

    [Fact]
    public void BuildGroupSection_emits_h2_with_group_key_and_description()
    {
        var sb = new StringBuilder();
        var group = new List<(Command, RtCommandInfo)> { MakeEntry("describe", "inspect") }
            .GroupBy(e => e.Item2.Category)
            .Single();

        DumpHelpCommand.BuildGroupSection(sb, group);

        var output = sb.ToString();
        Assert.Contains("## `rt inspect`", output);
        Assert.Contains(App.GroupDescriptions["inspect"], output);
    }

    [Fact]
    public void BuildGroupSection_contains_command_h3_heading()
    {
        var sb = new StringBuilder();
        var group = new List<(Command, RtCommandInfo)> { MakeEntry("outline", "inspect") }
            .GroupBy(e => e.Item2.Category)
            .Single();

        DumpHelpCommand.BuildGroupSection(sb, group);

        Assert.Contains("### outline", sb.ToString());
    }

    // ── BuildCommandSection ───────────────────────────────────────────────────────

    [Fact]
    public void BuildCommandSection_emits_h3_with_name()
    {
        var sb = new StringBuilder();
        var (cmd, info) = MakeEntry("describe", "inspect", "Describes a symbol");

        DumpHelpCommand.BuildCommandSection(sb, cmd, info);

        Assert.Contains("### describe", sb.ToString());
    }

    [Fact]
    public void BuildCommandSection_emits_description_in_italics()
    {
        var sb = new StringBuilder();
        var (cmd, info) = MakeEntry("describe", "inspect", "Describes a symbol");

        DumpHelpCommand.BuildCommandSection(sb, cmd, info);

        Assert.Contains("_Describes a symbol_", sb.ToString());
    }

    [Fact]
    public void BuildCommandSection_emits_readonly_badge_for_non_mutating_command()
    {
        var sb = new StringBuilder();
        var (cmd, info) = MakeEntry("describe", "inspect", mutates: false);

        DumpHelpCommand.BuildCommandSection(sb, cmd, info);

        Assert.Contains("**Read-only**", sb.ToString());
    }

    [Fact]
    public void BuildCommandSection_emits_mutation_badge_for_mutating_command()
    {
        var sb = new StringBuilder();
        var (cmd, info) = MakeEntry("rename", "refactor", mutates: true);

        DumpHelpCommand.BuildCommandSection(sb, cmd, info);

        Assert.Contains("**Mutation**", sb.ToString());
    }

    [Fact]
    public void BuildCommandSection_emits_json_output_badge()
    {
        var sb = new StringBuilder();
        var (cmd, info) = MakeEntry("describe", "inspect", jsonOutput: true);

        DumpHelpCommand.BuildCommandSection(sb, cmd, info);

        Assert.Contains("JSON output", sb.ToString());
    }

    [Fact]
    public void BuildCommandSection_emits_plain_text_badge_when_not_json()
    {
        var sb = new StringBuilder();
        var (cmd, info) = MakeEntry("rename", "refactor", jsonOutput: false);

        DumpHelpCommand.BuildCommandSection(sb, cmd, info);

        Assert.Contains("Plain-text output", sb.ToString());
    }

    [Fact]
    public void BuildCommandSection_emits_aliases_when_present()
    {
        var sb = new StringBuilder();
        var (cmd, info) = MakeEntry("find-refs", "inspect", aliases: ["refs", "fr"]);

        DumpHelpCommand.BuildCommandSection(sb, cmd, info);

        var output = sb.ToString();
        Assert.Contains("**Aliases:**", output);
        Assert.Contains("`refs`", output);
        Assert.Contains("`fr`", output);
    }

    [Fact]
    public void BuildCommandSection_omits_aliases_section_when_none()
    {
        var sb = new StringBuilder();
        var (cmd, info) = MakeEntry("describe", "inspect", aliases: null);

        DumpHelpCommand.BuildCommandSection(sb, cmd, info);

        Assert.DoesNotContain("**Aliases:**", sb.ToString());
    }

    [Fact]
    public void BuildCommandSection_emits_examples_in_code_fence()
    {
        var sb = new StringBuilder();
        var (cmd, info) = MakeEntry("describe", "inspect",
            examples: ["rt inspect describe Foo --solution x.slnx"]);

        DumpHelpCommand.BuildCommandSection(sb, cmd, info);

        var output = sb.ToString();
        Assert.Contains("```bash", output);
        Assert.Contains("rt inspect describe Foo --solution x.slnx", output);
        Assert.Contains("```", output);
    }

    [Fact]
    public void BuildCommandSection_emits_known_issues_when_present()
    {
        var sb = new StringBuilder();
        var (cmd, info) = MakeEntry("rename", "refactor",
            knownIssues: ["Known issue one", "Known issue two"]);

        DumpHelpCommand.BuildCommandSection(sb, cmd, info);

        var output = sb.ToString();
        Assert.Contains("**Known issues:**", output);
        Assert.Contains("- Known issue one", output);
        Assert.Contains("- Known issue two", output);
    }

    [Fact]
    public void BuildCommandSection_omits_known_issues_section_when_none()
    {
        var sb = new StringBuilder();
        var (cmd, info) = MakeEntry("describe", "inspect", knownIssues: null);

        DumpHelpCommand.BuildCommandSection(sb, cmd, info);

        Assert.DoesNotContain("**Known issues:**", sb.ToString());
    }

    [Fact]
    public void BuildCommandSection_ends_with_hr_separator()
    {
        var sb = new StringBuilder();
        var (cmd, info) = MakeEntry("describe", "inspect");

        DumpHelpCommand.BuildCommandSection(sb, cmd, info);

        Assert.Contains("---", sb.ToString());
    }

    // ── RenderMarkdown round-trip ─────────────────────────────────────────────────

    [Fact]
    public void RenderMarkdown_output_contains_all_group_sections()
    {
        // Use the real registry to verify structure is preserved after refactor.
        var snapshot = App.Commands
            .Select(e => (Cmd: e.Build(), e.Info))
            .ToList();

        var output = DumpHelpCommand.RenderMarkdown(snapshot);

        Assert.Contains("## `rt inspect`", output);
        Assert.Contains("## `rt analyze`", output);
        Assert.Contains("## `rt refactor`", output);
    }
}
