using System.CommandLine;
using System.Text;
using RoslynTools.Commands;
using RoslynTools.Core;
using Shouldly;

namespace RoslynTools.Tests;

/// <summary>
///     Unit tests for DumpHelpCommand helper methods extracted in US-033:
///     - BuildHeader
///     - BuildContents
///     - BuildGroupSection
///     - BuildCommandSection
///     Each helper is tested in isolation with a minimal synthetic registry.
/// </summary>
public sealed class DumpHelp
{
    // ── helpers ───────────────────────────────────────────────────────────────────

    private static (Command Cmd, RtCommandInfo Info) MakeEntry(
        string name,
        string category,
        string description = "A description",
        bool mutates = false,
        bool jsonOutput = false,
        string[]? aliases = null,
        string[]? knownIssues = null,
        string[]? examples = null)
    {
        var info = new RtCommandInfo(
            name,
            mutates,
            jsonOutput,
            category,
            "Use when needed.",
            examples ?? [$"rt {category} {name}"],
            knownIssues,
            aliases);

        var cmd = new Command(name, description);
        return (cmd, info);
    }

    // ── BuildHeader ───────────────────────────────────────────────────────────────

    [Fact]
    public void builds_header_emits_h1_title()
    {
        var sb = new StringBuilder();
        var registry = new List<(Command, RtCommandInfo)> { MakeEntry("foo", "inspect") };

        DumpHelpCommand.BuildHeader(sb, registry);

        sb.ToString().ShouldContain("# rt Commands", Case.Sensitive);
    }

    [Fact]
    public void builds_header_includes_total_count()
    {
        var sb = new StringBuilder();
        var registry = new List<(Command, RtCommandInfo)>
        {
            MakeEntry("foo", "inspect"),
            MakeEntry("bar", "analyze")
        };

        DumpHelpCommand.BuildHeader(sb, registry);

        sb.ToString().ShouldContain("**2**", Case.Sensitive);
    }

    [Fact]
    public void builds_header_includes_autogenerated_notice()
    {
        var sb = new StringBuilder();
        var registry = new List<(Command, RtCommandInfo)> { MakeEntry("foo", "inspect") };

        DumpHelpCommand.BuildHeader(sb, registry);

        sb.ToString().ShouldContain("Auto-generated", Case.Sensitive);
    }

    // ── BuildContents ─────────────────────────────────────────────────────────────

    [Fact]
    public void builds_contents_emits_contents_heading()
    {
        var sb = new StringBuilder();
        var groups = new List<(Command, RtCommandInfo)> { MakeEntry("describe", "inspect") }
            .GroupBy(e => e.Item2.Category)
            .OrderBy(g => g.Key);

        DumpHelpCommand.BuildContents(sb, groups);

        sb.ToString().ShouldContain("## Contents", Case.Sensitive);
    }

    [Fact]
    public void builds_contents_lists_each_group_key()
    {
        var sb = new StringBuilder();
        var groups = new List<(Command, RtCommandInfo)>
            {
                MakeEntry("describe", "inspect"),
                MakeEntry("circular-deps", "analyze")
            }
            .GroupBy(e => e.Item2.Category)
            .OrderBy(g => g.Key);

        DumpHelpCommand.BuildContents(sb, groups);

        var output = sb.ToString();
        output.ShouldContain("rt inspect", Case.Sensitive);
        output.ShouldContain("rt analyze", Case.Sensitive);
    }

    [Fact]
    public void builds_contents_includes_anchor_link_for_command_name()
    {
        var sb = new StringBuilder();
        var groups = new List<(Command, RtCommandInfo)> { MakeEntry("describe", "inspect") }
            .GroupBy(e => e.Item2.Category)
            .OrderBy(g => g.Key);

        DumpHelpCommand.BuildContents(sb, groups);

        sb.ToString().ShouldContain("[`describe`](#describe)", Case.Sensitive);
    }

    [Fact]
    public void builds_contents_includes_aliases_when_present()
    {
        var sb = new StringBuilder();
        var groups = new List<(Command, RtCommandInfo)>
            {
                MakeEntry("find-refs", "inspect", aliases: ["refs"])
            }
            .GroupBy(e => e.Item2.Category)
            .OrderBy(g => g.Key);

        DumpHelpCommand.BuildContents(sb, groups);

        sb.ToString().ShouldContain("refs", Case.Sensitive);
    }

    // ── BuildGroupSection ─────────────────────────────────────────────────────────

    [Fact]
    public void builds_group_section_emits_h2_with_group_key_and_description()
    {
        var sb = new StringBuilder();
        var group = new List<(Command, RtCommandInfo)> { MakeEntry("describe", "inspect") }
            .GroupBy(e => e.Item2.Category)
            .Single();

        DumpHelpCommand.BuildGroupSection(sb, group);

        var output = sb.ToString();
        output.ShouldContain("## `rt inspect`", Case.Sensitive);
        output.ShouldContain(App.GroupDescriptions["inspect"], Case.Sensitive);
    }

    [Fact]
    public void builds_group_section_contains_command_h3_heading()
    {
        var sb = new StringBuilder();
        var group = new List<(Command, RtCommandInfo)> { MakeEntry("outline", "inspect") }
            .GroupBy(e => e.Item2.Category)
            .Single();

        DumpHelpCommand.BuildGroupSection(sb, group);

        sb.ToString().ShouldContain("### outline", Case.Sensitive);
    }

    // ── BuildCommandSection ───────────────────────────────────────────────────────

    [Fact]
    public void builds_command_section_emits_h3_with_name()
    {
        var sb = new StringBuilder();
        var (cmd, info) = MakeEntry("describe", "inspect", "Describes a symbol");

        DumpHelpCommand.BuildCommandSection(sb, cmd, info);

        sb.ToString().ShouldContain("### describe", Case.Sensitive);
    }

    [Fact]
    public void builds_command_section_emits_description_in_italics()
    {
        var sb = new StringBuilder();
        var (cmd, info) = MakeEntry("describe", "inspect", "Describes a symbol");

        DumpHelpCommand.BuildCommandSection(sb, cmd, info);

        sb.ToString().ShouldContain("_Describes a symbol_", Case.Sensitive);
    }

    [Fact]
    public void builds_command_section_emits_readonly_badge_for_non_mutating_command()
    {
        var sb = new StringBuilder();
        var (cmd, info) = MakeEntry("describe", "inspect", mutates: false);

        DumpHelpCommand.BuildCommandSection(sb, cmd, info);

        sb.ToString().ShouldContain("**Read-only**", Case.Sensitive);
    }

    [Fact]
    public void builds_command_section_emits_mutation_badge_for_mutating_command()
    {
        var sb = new StringBuilder();
        var (cmd, info) = MakeEntry("rename", "refactor", mutates: true);

        DumpHelpCommand.BuildCommandSection(sb, cmd, info);

        sb.ToString().ShouldContain("**Mutation**", Case.Sensitive);
    }

    [Fact]
    public void builds_command_section_emits_json_output_badge()
    {
        var sb = new StringBuilder();
        var (cmd, info) = MakeEntry("describe", "inspect", jsonOutput: true);

        DumpHelpCommand.BuildCommandSection(sb, cmd, info);

        sb.ToString().ShouldContain("JSON output", Case.Sensitive);
    }

    [Fact]
    public void builds_command_section_emits_plain_text_badge_when_not_json()
    {
        var sb = new StringBuilder();
        var (cmd, info) = MakeEntry("rename", "refactor", jsonOutput: false);

        DumpHelpCommand.BuildCommandSection(sb, cmd, info);

        sb.ToString().ShouldContain("Plain-text output", Case.Sensitive);
    }

    [Fact]
    public void builds_command_section_emits_aliases_when_present()
    {
        var sb = new StringBuilder();
        var (cmd, info) = MakeEntry("find-refs", "inspect", aliases: ["refs", "fr"]);

        DumpHelpCommand.BuildCommandSection(sb, cmd, info);

        var output = sb.ToString();
        output.ShouldContain("**Aliases:**", Case.Sensitive);
        output.ShouldContain("`refs`", Case.Sensitive);
        output.ShouldContain("`fr`", Case.Sensitive);
    }

    [Fact]
    public void builds_command_section_omits_aliases_section_when_none()
    {
        var sb = new StringBuilder();
        var (cmd, info) = MakeEntry("describe", "inspect", aliases: null);

        DumpHelpCommand.BuildCommandSection(sb, cmd, info);

        sb.ToString().ShouldNotContain("**Aliases:**", Case.Sensitive);
    }

    [Fact]
    public void builds_command_section_emits_examples_in_code_fence()
    {
        var sb = new StringBuilder();
        var (cmd, info) = MakeEntry("describe", "inspect",
            examples: ["rt inspect describe Foo --solution x.slnx"]);

        DumpHelpCommand.BuildCommandSection(sb, cmd, info);

        var output = sb.ToString();
        output.ShouldContain("```bash", Case.Sensitive);
        output.ShouldContain("rt inspect describe Foo --solution x.slnx", Case.Sensitive);
        output.ShouldContain("```", Case.Sensitive);
    }

    [Fact]
    public void builds_command_section_emits_known_issues_when_present()
    {
        var sb = new StringBuilder();
        var (cmd, info) = MakeEntry("rename", "refactor",
            knownIssues: ["Known issue one", "Known issue two"]);

        DumpHelpCommand.BuildCommandSection(sb, cmd, info);

        var output = sb.ToString();
        output.ShouldContain("**Known issues:**", Case.Sensitive);
        output.ShouldContain("- Known issue one", Case.Sensitive);
        output.ShouldContain("- Known issue two", Case.Sensitive);
    }

    [Fact]
    public void builds_command_section_omits_known_issues_section_when_none()
    {
        var sb = new StringBuilder();
        var (cmd, info) = MakeEntry("describe", "inspect", knownIssues: null);

        DumpHelpCommand.BuildCommandSection(sb, cmd, info);

        sb.ToString().ShouldNotContain("**Known issues:**", Case.Sensitive);
    }

    [Fact]
    public void builds_command_section_ends_with_hr_separator()
    {
        var sb = new StringBuilder();
        var (cmd, info) = MakeEntry("describe", "inspect");

        DumpHelpCommand.BuildCommandSection(sb, cmd, info);

        sb.ToString().ShouldContain("---", Case.Sensitive);
    }

    // ── RenderMarkdown round-trip ─────────────────────────────────────────────────

    [Fact]
    public void renders_markdown_output_with_all_group_sections()
    {
        // Use the real registry to verify structure is preserved after refactor.
        var snapshot = App.Commands
            .Select(e => (Cmd: e.Build(), e.Info))
            .ToList();

        var output = DumpHelpCommand.RenderMarkdown(snapshot);

        output.ShouldContain("## `rt inspect`", Case.Sensitive);
        output.ShouldContain("## `rt analyze`", Case.Sensitive);
        output.ShouldContain("## `rt refactor`", Case.Sensitive);
    }
}
