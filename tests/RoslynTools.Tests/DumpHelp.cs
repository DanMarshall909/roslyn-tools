using System.CommandLine;
using System.Text;
using RoslynTools.Commands;
using RoslynTools.Core;
using RoslynTools.Core.Output;
using Shouldly;

namespace RoslynTools.Tests;

/// <summary>
///     Unit tests for DumpHelpCommand helper methods extracted in US-033:
///     - BuildHeader
///     - BuildContents
///     - BuildGroupSection
///     - BuildCommandSection
///     Each helper is tested in isolation with a minimal synthetic registry.
/// </summary>
public sealed class DumpHelp
{
    // ── helpers ───────────────────────────────────────────────────────────────────

    private static (Command Cmd, RtCommandInfo Info) MakeEntry(
        string name,
        string category,
        string description = "A description",
        bool mutates = false,
        bool jsonOutput = false,
        string[]? aliases = null,
        string[]? knownIssues = null,
        string[]? examples = null)
    {
        var info = new RtCommandInfo(
            name,
            mutates,
            jsonOutput,
            category,
            "Use when needed.",
            examples ?? [$"rt {category} {name}"],
            knownIssues,
            aliases);

        var cmd = new Command(name, description);
        return (cmd, info);
    }

    // ── BuildHeader ───────────────────────────────────────────────────────────────

    [Fact]
    public void builds_header_emits_h1_title()
    {
        var sb = new StringBuilder();
        var registry = new List<(Command, RtCommandInfo)> { MakeEntry("foo", "inspect") };

        DumpHelpCommand.BuildHeader(sb, registry);

        sb.ToString().ShouldContain("# rt Commands", Case.Sensitive);
    }

    [Fact]
    public void builds_header_includes_total_count()
    {
        var sb = new StringBuilder();
        var registry = new List<(Command, RtCommandInfo)>
        {
            MakeEntry("foo", "inspect"),
            MakeEntry("bar", "analyze")
        };

        DumpHelpCommand.BuildHeader(sb, registry);

        sb.ToString().ShouldContain("**2**", Case.Sensitive);
    }

    [Fact]
    public void builds_header_includes_autogenerated_notice()
    {
        var sb = new StringBuilder();
        var registry = new List<(Command, RtCommandInfo)> { MakeEntry("foo", "inspect") };

        DumpHelpCommand.BuildHeader(sb, registry);

        sb.ToString().ShouldContain("Auto-generated", Case.Sensitive);
    }

    // ── BuildContents ─────────────────────────────────────────────────────────────

    [Fact]
    public void builds_contents_emits_contents_heading()
    {
        var sb = new StringBuilder();
        var groups = new List<(Command, RtCommandInfo)> { MakeEntry("describe", "inspect") }
            .GroupBy(e => e.Item2.Category)
            .OrderBy(g => g.Key);

        DumpHelpCommand.BuildContents(sb, groups);

        sb.ToString().ShouldContain("## Contents", Case.Sensitive);
    }

    [Fact]
    public void builds_contents_lists_each_group_key()
    {
        var sb = new StringBuilder();
        var groups = new List<(Command, RtCommandInfo)>
            {
                MakeEntry("describe", "inspect"),
                MakeEntry("circular-deps", "analyze")
            }
            .GroupBy(e => e.Item2.Category)
            .OrderBy(g => g.Key);

        DumpHelpCommand.BuildContents(sb, groups);

        var output = sb.ToString();
        output.ShouldContain("rt inspect", Case.Sensitive);
        output.ShouldContain("rt analyze", Case.Sensitive);
    }

    [Fact]
    public void builds_contents_includes_anchor_link_for_command_name()
    {
        var sb = new StringBuilder();
        var groups = new List<(Command, RtCommandInfo)> { MakeEntry("describe", "inspect") }
            .GroupBy(e => e.Item2.Category)
            .OrderBy(g => g.Key);

        DumpHelpCommand.BuildContents(sb, groups);

        sb.ToString().ShouldContain("[`describe`](#describe)", Case.Sensitive);
    }

