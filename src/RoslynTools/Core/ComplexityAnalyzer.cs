using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace RoslynTools.Core;

/// <summary>
/// MethodComplexity
/// </summary>
internal record MethodComplexity(
    string Method,
    string Type,
    string Namespace,
    string File,
    int Line,
    int Cyclomatic,
    int Cognitive,
    int Loc,
    int Params);

/// <summary>
/// TypeComplexityRollup
/// </summary>
internal record TypeComplexityRollup(
    string Type,
    string Namespace,
    int MethodCount,
    int CyclomaticTotal,
    int CognitiveTotal,
    int LocTotal,
    int ParamsTotal);

/// <summary>
/// NamespaceComplexityRollup
/// </summary>
internal record NamespaceComplexityRollup(
    string Namespace,
    int MethodCount,
    int CyclomaticTotal,
    int CognitiveTotal,
    int LocTotal,
    int ParamsTotal);

/// <summary>
/// ComplexityReport
/// </summary>
internal record ComplexityReport(
    IReadOnlyList<MethodComplexity> Methods,
    IReadOnlyList<TypeComplexityRollup> TypeRollups,
    IReadOnlyList<NamespaceComplexityRollup> NamespaceRollups,
    string RollupScope,
    int MatchingMethodCount,
    int TotalTypeRollupCount,
    int TotalNamespaceRollupCount);

/// <summary>
/// ComplexityAnalyzer
/// </summary>
internal static class ComplexityAnalyzer
{
    internal static async Task<ComplexityReport> AnalyzeAsync(
        Solution solution,
        int threshold = 0,
        string sort = "cyclomatic",
        int top = 0,
        CancellationToken cancellationToken = default)
    {
        var allMethods = new List<MethodComplexity>();

        foreach (var project in solution.Projects)
            foreach (var document in project.Documents)
            {
                cancellationToken.ThrowIfCancellationRequested();
                var filePath = document.FilePath ?? string.Empty;

                if (IsGeneratedFile(filePath))
                    continue;

                var root = await document.GetSyntaxRootAsync(cancellationToken).ConfigureAwait(false);
                if (root is null)
                    continue;

                var text = await document.GetTextAsync(cancellationToken).ConfigureAwait(false);
                var sourceText = text.ToString();

                if (sourceText.Contains("<auto-generated>"))
                    continue;

                foreach (var method in CollectMethods(root, filePath))
                    allMethods.Add(method);
            }

        // Compute rollups over ALL methods before filtering
        var typeRollups = ComputeTypeRollups(allMethods);
        var nsRollups = ComputeNamespaceRollups(allMethods);

        // Filter by threshold (any metric >= threshold)
        var filtered = threshold > 0
            ? allMethods.Where(m => m.Cyclomatic >= threshold
                                    || m.Cognitive >= threshold
                                    || m.Loc >= threshold
                                    || m.Params >= threshold)
            : allMethods;

        // Sort descending by chosen metric, ties by Method ascending
        filtered = sort.ToLowerInvariant() switch
        {
            "cognitive" => filtered.OrderByDescending(m => m.Cognitive).ThenBy(m => m.Method),
            "loc" => filtered.OrderByDescending(m => m.Loc).ThenBy(m => m.Method),
            "params" => filtered.OrderByDescending(m => m.Params).ThenBy(m => m.Method),
            _ => filtered.OrderByDescending(m => m.Cyclomatic).ThenBy(m => m.Method)
        };

        var matchingMethods = filtered.ToList();
        var methods = top > 0 ? matchingMethods.Take(top).ToList() : matchingMethods;
        var totalTypeRollupCount = typeRollups.Count;
        var totalNamespaceRollupCount = nsRollups.Count;
        if (top > 0)
        {
            var selectedTypes = methods.Select(method => method.Type).ToHashSet(StringComparer.Ordinal);
            var selectedNamespaces = methods.Select(method => method.Namespace).ToHashSet(StringComparer.Ordinal);
            typeRollups = typeRollups.Where(rollup => selectedTypes.Contains(rollup.Type)).ToList();
            nsRollups = nsRollups.Where(rollup => selectedNamespaces.Contains(rollup.Namespace)).ToList();
        }

        return new ComplexityReport(
            methods,
            typeRollups,
            nsRollups,
            top > 0 ? "returnedMethods" : "all",
            matchingMethods.Count,
            totalTypeRollupCount,
            totalNamespaceRollupCount);
    }

    private static bool IsGeneratedFile(string filePath)
    {
        return filePath.EndsWith(".g.cs", StringComparison.OrdinalIgnoreCase)
               || filePath.EndsWith(".Designer.cs", StringComparison.OrdinalIgnoreCase);
    }

    private static IEnumerable<MethodComplexity> CollectMethods(SyntaxNode root, string filePath)
    {
        // Walk all descendant nodes looking for the member kinds we care about
        foreach (var node in root.DescendantNodes())
        {
            MethodComplexity? mc = null;

            if (node is MethodDeclarationSyntax methodDecl)
            {
                // Skip abstract methods
                if (methodDecl.Modifiers.Any(m => m.IsKind(SyntaxKind.AbstractKeyword)))
                    continue;

                // Skip partial methods without a body
                if (methodDecl.Modifiers.Any(m => m.IsKind(SyntaxKind.PartialKeyword))
                    && methodDecl.Body is null
                    && methodDecl.ExpressionBody is null)
                    continue;

                mc = BuildMethodComplexity(methodDecl.Identifier.Text, methodDecl, filePath,
                    methodDecl.Body, methodDecl.ExpressionBody, methodDecl.ParameterList,
                    methodDecl.ParameterList.Parameters.Count > 0
                    && methodDecl.ParameterList.Parameters[0].Modifiers
                        .Any(m => m.IsKind(SyntaxKind.ThisKeyword)));
            }
            else if (node is ConstructorDeclarationSyntax ctorDecl)
            {
                if (ctorDecl.Body is null && ctorDecl.ExpressionBody is null)
                    continue;

                mc = BuildMethodComplexity(ctorDecl.Identifier.Text, ctorDecl, filePath,
                    ctorDecl.Body, ctorDecl.ExpressionBody, ctorDecl.ParameterList,
                    false);
            }
            else if (node is AccessorDeclarationSyntax accessorDecl)
            {
                // Skip auto-property accessors (no body)
                if (accessorDecl.Body is null && accessorDecl.ExpressionBody is null)
                    continue;

                // Property/event name + accessor keyword: "X.get", "X.set", "X.init"
                var memberName = accessorDecl.Parent?.Parent switch
                {
                    PropertyDeclarationSyntax prop => prop.Identifier.Text,
                    EventDeclarationSyntax evt => evt.Identifier.Text,
                    _ => "?"
                };
                var accessorName = $"{memberName}.{accessorDecl.Keyword.Text}";
                mc = BuildMethodComplexity(accessorName, accessorDecl, filePath,
                    accessorDecl.Body, accessorDecl.ExpressionBody, null,
                    false);
            }
            else if (node is LocalFunctionStatementSyntax localFunc)
            {
                if (localFunc.Modifiers.Any(m => m.IsKind(SyntaxKind.AbstractKeyword)))
                    continue;

                if (localFunc.Body is null && localFunc.ExpressionBody is null)
                    continue;

                mc = BuildMethodComplexity(localFunc.Identifier.Text, localFunc, filePath,
                    localFunc.Body, localFunc.ExpressionBody, localFunc.ParameterList,
                    false);
            }

            if (mc is not null)
                yield return mc;
        }
    }

    private static MethodComplexity BuildMethodComplexity(
        string name,
        SyntaxNode memberNode,
        string filePath,
        BlockSyntax? body,
        ArrowExpressionClauseSyntax? expressionBody,
        ParameterListSyntax? parameterList,
        bool isExtensionMethod)
    {
        // Resolve containing type and namespace
        var (typeName, namespaceName) = GetContainingTypeAndNamespace(memberNode);

        var lineSpan = memberNode.GetLocation().GetLineSpan();
        var line = lineSpan.StartLinePosition.Line + 1;

        var cyclomatic = ComputeCyclomatic(memberNode);
        var cognitive = ComputeCognitive(memberNode);
        var loc = ComputeLoc(body, expressionBody);
        var paramCount = parameterList is null ? 0 : parameterList.Parameters.Count;
        if (isExtensionMethod && paramCount > 0)
            paramCount--;

        // FQN: Namespace.Type (empty namespace → just Type)
        var fqnType = string.IsNullOrEmpty(namespaceName) ? typeName : $"{namespaceName}.{typeName}";
        var fqnMethod = $"{fqnType}.{name}";

        return new MethodComplexity(fqnMethod, fqnType, namespaceName, filePath, line,
            cyclomatic, cognitive, loc, paramCount);
    }

    private static (string TypeName, string Namespace) GetContainingTypeAndNamespace(SyntaxNode node)
    {
        // Walk up to find containing type
        var parent = node.Parent;
        while (parent is not null)
        {
            if (parent is TypeDeclarationSyntax typeDecl)
            {
                var typeName = typeDecl.Identifier.Text;
                var ns = GetNamespace(typeDecl);
                return (typeName, ns);
            }

            parent = parent.Parent;
        }

        return (string.Empty, string.Empty);
    }

    private static string GetNamespace(SyntaxNode node)
    {
        var parent = node.Parent;
        while (parent is not null)
        {
            if (parent is FileScopedNamespaceDeclarationSyntax fsns)
                return fsns.Name.ToString();
            if (parent is NamespaceDeclarationSyntax ns)
                return ns.Name.ToString();
            parent = parent.Parent;
        }

        return string.Empty;
    }

    private static int ComputeCyclomatic(SyntaxNode root)
    {
        var count = 1; // base complexity

        foreach (var node in root.DescendantNodes())
            switch (node)
            {
                case IfStatementSyntax:
                    count++;
                    break;

                case SwitchSectionSyntax switchSection:
                    // Count non-default labels
                    count += switchSection.Labels.Count(l => l is not DefaultSwitchLabelSyntax);
                    break;

                case SwitchExpressionArmSyntax arm:
                    // Count non-discard patterns
                    if (arm.Pattern is not DiscardPatternSyntax)
                        count++;
                    break;

                case ForStatementSyntax:
                case ForEachStatementSyntax:
                case WhileStatementSyntax:
                case DoStatementSyntax:
                case CatchClauseSyntax:
                case ConditionalExpressionSyntax:
                    count++;
                    break;

                case BinaryExpressionSyntax binary:
                    if (binary.IsKind(SyntaxKind.CoalesceExpression)
                        || binary.IsKind(SyntaxKind.LogicalAndExpression)
                        || binary.IsKind(SyntaxKind.LogicalOrExpression))
                        count++;
                    break;

                case ConditionalAccessExpressionSyntax:
                    count++;
                    break;

                case AssignmentExpressionSyntax assignment:
                    if (assignment.IsKind(SyntaxKind.CoalesceAssignmentExpression))
                        count++;
                    break;
            }

        return count;
    }

    private static int ComputeCognitive(SyntaxNode methodNode)
    {
        var total = 0;
        WalkCognitive(methodNode, 0, ref total);

        // Count logical operator sequences in expressions
        total += CountLogicalOperatorSequences(methodNode);

        // Count recursive calls
        var methodName = GetMethodName(methodNode);
        if (methodName is not null)
            foreach (var invocation in methodNode.DescendantNodes().OfType<InvocationExpressionSyntax>())
            {
                var exprName = GetSimpleInvocationName(invocation);
                if (exprName == methodName)
                    total++;
            }

        return total;
    }

    private static void WalkCognitive(SyntaxNode node, int depth, ref int total)
    {
        // We only recurse into the body of the method; the method node itself doesn't count
        foreach (var child in node.ChildNodes()) WalkCognitiveNode(child, depth, ref total);
    }

    private static void WalkCognitiveNode(SyntaxNode node, int depth, ref int total)
    {
        var isStructural = false;
        var incrementDepth = false;

        switch (node)
        {
            case IfStatementSyntax ifStmt:
                // Check if this is an else-if (parent is ElseClauseSyntax)
                if (node.Parent is ElseClauseSyntax)
                {
                    // else-if: cost = 1, no depth increment
                    total += 1;
                    // Continue visiting body and else with same depth
                    if (ifStmt.Statement is not null)
                        WalkCognitiveNode(ifStmt.Statement, depth, ref total);
                    if (ifStmt.Else is not null)
                        WalkCognitiveNode(ifStmt.Else, depth, ref total);
                    return;
                }

                total += 1 + depth;
                isStructural = true;
                incrementDepth = true;
                break;

            case ElseClauseSyntax elseClause:
                // Plain else (not else-if): +1, no depth increment
                // If the else body is an if statement, that's handled as else-if above
                if (elseClause.Statement is not IfStatementSyntax) total += 1;
                // Walk children with same depth
                foreach (var child in elseClause.ChildNodes())
                    WalkCognitiveNode(child, depth, ref total);
                return;

            case ForStatementSyntax:
            case ForEachStatementSyntax:
            case WhileStatementSyntax:
            case DoStatementSyntax:
                total += 1 + depth;
                isStructural = true;
                incrementDepth = true;
                break;

            case CatchClauseSyntax:
                total += 1 + depth;
                isStructural = true;
                incrementDepth = true;
                break;

            case ConditionalExpressionSyntax:
                total += 1 + depth;
                isStructural = true;
                incrementDepth = true;
                break;

            case SwitchStatementSyntax:
            case SwitchExpressionSyntax:
                total += 1 + depth;
                isStructural = true;
                incrementDepth = true;
                break;
        }

        if (isStructural)
        {
            var childDepth = incrementDepth ? depth + 1 : depth;
            foreach (var child in node.ChildNodes())
                WalkCognitiveNode(child, childDepth, ref total);
        }
        else
        {
            foreach (var child in node.ChildNodes())
                WalkCognitiveNode(child, depth, ref total);
        }
    }

    private static int CountLogicalOperatorSequences(SyntaxNode methodNode)
    {
        // For each expression context, count operator-type changes (run boundaries)
        // A run of consecutive &&: 1 penalty. A run of consecutive ||: 1 penalty.
        // A switch from && to ||: +1 more penalty.
        var total = 0;

        foreach (var expr in methodNode.DescendantNodes().OfType<BinaryExpressionSyntax>())
        {
            // Only count at the "top" of each logical chain (parent is not also a logical binary)
            if (expr.Parent is BinaryExpressionSyntax parentBinary
                && (parentBinary.IsKind(SyntaxKind.LogicalAndExpression)
                    || parentBinary.IsKind(SyntaxKind.LogicalOrExpression)))
                continue;

            if (!expr.IsKind(SyntaxKind.LogicalAndExpression)
                && !expr.IsKind(SyntaxKind.LogicalOrExpression))
                continue;

            // Collect the flat sequence of operators for this chain
            var ops = new List<SyntaxKind>();
            CollectLogicalOps(expr, ops);

            if (ops.Count == 0)
                continue;

            // Count sequences: +1 per run (so 1 operator = 1; same-type run = 1; each type change = +1)
            var prev = ops[0];
            total += 1; // first run
            for (var i = 1; i < ops.Count; i++)
                if (ops[i] != prev)
                {
                    total += 1;
                    prev = ops[i];
                }
        }

        return total;
    }

    private static void CollectLogicalOps(BinaryExpressionSyntax expr, List<SyntaxKind> ops)
    {
        if (expr.Left is BinaryExpressionSyntax leftBinary
            && (leftBinary.IsKind(SyntaxKind.LogicalAndExpression)
                || leftBinary.IsKind(SyntaxKind.LogicalOrExpression)))
            CollectLogicalOps(leftBinary, ops);

        if (expr.IsKind(SyntaxKind.LogicalAndExpression) || expr.IsKind(SyntaxKind.LogicalOrExpression))
            ops.Add(expr.Kind());

        if (expr.Right is BinaryExpressionSyntax rightBinary
            && (rightBinary.IsKind(SyntaxKind.LogicalAndExpression)
                || rightBinary.IsKind(SyntaxKind.LogicalOrExpression)))
            CollectLogicalOps(rightBinary, ops);
    }

    private static string? GetMethodName(SyntaxNode node)
    {
        return node switch
        {
            MethodDeclarationSyntax m => m.Identifier.Text,
            LocalFunctionStatementSyntax lf => lf.Identifier.Text,
            _ => null
        };
    }

    private static string? GetSimpleInvocationName(InvocationExpressionSyntax invocation)
    {
        return invocation.Expression switch
        {
            IdentifierNameSyntax id => id.Identifier.Text,
            MemberAccessExpressionSyntax ma => ma.Name.Identifier.Text,
            _ => null
        };
    }

    private static int ComputeLoc(BlockSyntax? body, ArrowExpressionClauseSyntax? expressionBody)
    {
        if (expressionBody is not null)
            return 1;

        if (body is null)
            return 0;

        var text = body.ToString();
        var lines = text.Split('\n');

        // Collect comment spans from block comments
        var blockCommentRanges = CollectBlockCommentRanges(text);

        var lineCount = 0;
        var charOffset = 0;

        foreach (var rawLine in lines)
        {
            var line = rawLine.TrimEnd('\r');
            var trimmed = line.TrimStart();

            // Skip blank lines
            if (trimmed.Length == 0)
            {
                charOffset += rawLine.Length + 1;
                continue;
            }

            // Skip pure comment lines (// ...)
            if (trimmed.StartsWith("//", StringComparison.Ordinal))
            {
                charOffset += rawLine.Length + 1;
                continue;
            }

            // Skip lines entirely within a block comment (no other tokens)
            if (IsEntirelyInBlockComment(charOffset, rawLine.Length, blockCommentRanges, trimmed))
            {
                charOffset += rawLine.Length + 1;
                continue;
            }

            // Skip the opening { and closing } of the block
            if (trimmed == "{" || trimmed == "}")
            {
                charOffset += rawLine.Length + 1;
                continue;
            }

            lineCount++;
            charOffset += rawLine.Length + 1;
        }

        return lineCount;
    }

    private static List<(int Start, int End)> CollectBlockCommentRanges(string text)
    {
        var ranges = new List<(int, int)>();
        var i = 0;
        while (i < text.Length - 1)
            if (text[i] == '/' && text[i + 1] == '*')
            {
                var start = i;
                i += 2;
                while (i < text.Length - 1 && !(text[i] == '*' && text[i + 1] == '/'))
                    i++;
                var end = i + 2;
                ranges.Add((start, end));
                i = end;
            }
            else
            {
                i++;
            }

        return ranges;
    }

    private static bool IsEntirelyInBlockComment(int lineStart, int lineLength, List<(int Start, int End)> ranges,
        string trimmed)
    {
        // Single-line block comment: /* ... */ with nothing else on the line
        if (trimmed.StartsWith("/*", StringComparison.Ordinal) && trimmed.EndsWith("*/", StringComparison.Ordinal))
            return true;

        // Line fully enclosed inside a multi-line block comment span.
        var contentEnd = lineStart + lineLength;
        foreach (var (start, end) in ranges)
            if (start <= lineStart && contentEnd <= end)
                return true;

        return false;
    }

    private static List<TypeComplexityRollup> ComputeTypeRollups(List<MethodComplexity> methods)
    {
        return methods
            .GroupBy(m => (m.Type, m.Namespace))
            .Select(g => new TypeComplexityRollup(
                g.Key.Type,
                g.Key.Namespace,
                g.Count(),
                g.Sum(m => m.Cyclomatic),
                g.Sum(m => m.Cognitive),
                g.Sum(m => m.Loc),
                g.Sum(m => m.Params)))
            .OrderByDescending(r => r.CyclomaticTotal)
            .ToList();
    }

    private static List<NamespaceComplexityRollup> ComputeNamespaceRollups(List<MethodComplexity> methods)
    {
        return methods
            .GroupBy(m => m.Namespace)
            .Select(g => new NamespaceComplexityRollup(
                g.Key,
                g.Count(),
                g.Sum(m => m.Cyclomatic),
                g.Sum(m => m.Cognitive),
                g.Sum(m => m.Loc),
                g.Sum(m => m.Params)))
            .OrderByDescending(r => r.CyclomaticTotal)
            .ToList();
    }
}
